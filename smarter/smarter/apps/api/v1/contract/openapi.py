"""
The OpenAPI 3.1 document of the Smarter api, generated from Pydantic models.

The document covers the apis that the ``smarter`` cli and the SDKs call, family by family:

- the cli api (``/api/v1/cli/``), to apply, get, describe, validate and delete the resources that
  SAM manifests declare,
- the chat api (``/api/v1/llm-clients/{id}/config/`` and ``.../prompt/``), to chat with an
  LLMClient, as JSON or as a stream of Server-Sent Events,
- the REST reads of the resource families: the LLMClients', Guardrails', Secrets', MCPClients',
  vectorstores', LLMHosts', plugins', Providers' and Proxies', whose responses are built from each
  app's contract models, e.g.
  :mod:`smarter.apps.llmclient.contract.models`. Only the reads are published: clients write
  through the cli api's manifests, which the brokers validate.

It is built from:

- the SAM models of every kind (:func:`smarter.apps.api.v1.contract.sam.sam_models`),
- the Smarter Journal api contract (:mod:`smarter.lib.journal.contract.models`), the envelope and
  the errors of every response,
- the Smarter Chat api contract (:mod:`smarter.apps.prompt.contract.models`), the requests,
  responses and progress events of the chat api, and the chat configuration and completion of
  the cli's prompt commands,
- the models of the other commands' data (:mod:`smarter.apps.api.v1.contract.models`),

so a change to any of them changes the document. ``manage.py export_api_contract`` writes it to
``openapi.json``, beside this module, and a test fails if the committed file is out of date, or if a
route of a family in :data:`DOCUMENTED_URLCONFS` is neither in the document nor in
:data:`UNDOCUMENTED_ROUTES`.

The live Swagger and Redoc pages (``/docs/swagger/``) are generated by drf-yasg from the views, and
describe every api of the platform in OpenAPI 2. This document describes fewer apis, but types their
requests and responses, so that clients can be generated from it.
"""

